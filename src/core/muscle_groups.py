def group_of(muscle: str) -> str:
    """取细分肌群所属的粗组；未登记的名字归入"其他"。

    未登记时返回"其他"而不是抛异常：动作库是可扩充的数据，线上不该因为
    多了一个新标注就把整张统计打挂。真正的兜底在测试里——它会在开发阶段
    用动作库的全量肌群名把遗漏直接暴露出来。
    """
    return _MUSCLE_TO_GROUP.get((muscle or "").strip(), OTHER_GROUP)


def is_known(muscle: str) -> bool:
    """该肌群名是否已在映射表里登记（供测试与数据体检使用）。"""
    return (muscle or "").strip() in _MUSCLE_TO_GROUP


def known_muscles() -> frozenset[str]:
    """已登记的肌群名集合。"""
    return frozenset(_MUSCLE_TO_GROUP)
